// The About and editorial-policy copy (docs/editorial/about-page/{locale}.md,
// the editorial source, F12) as a typed module for the app and the prerender:
//
//   node scripts/seo/about-content.mjs        (rewrites src/about/aboutContent.ts)
//
// tests/about.test.mjs fails if the module and the Markdown ever differ.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ABOUT_LOCALES = ["zh-CN", "zh-TW", "en", "ur", "hi"];
/** Stable anchors for the four sections, in order (links such as "Our sources and checks" use them). */
export const ABOUT_SECTION_IDS = ["sources", "preparation", "corrections", "independence"];

/** Title (H1), search description, intro paragraphs and the H2 sections with their paragraphs. */
export function parseAboutMarkdown(text) {
  const blocks = text.replace(/\r\n/g, "\n").split(/\n{2,}/).map((block) => block.trim()).filter(Boolean);
  const title = /^# (.+)$/.exec(blocks.shift() ?? "")?.[1];
  const description = /^\*\*[^*]+\*\* — (.+)$/s.exec(blocks.shift() ?? "")?.[1];
  if (!title || !description) throw new Error("About copy must start with the H1 and the **…** — search description");
  const intro = [];
  const sections = [];
  for (const block of blocks) {
    const heading = /^## (.+)$/.exec(block);
    if (heading) sections.push({ heading: heading[1], paragraphs: [] });
    else if (/^#/.test(block)) throw new Error(`unexpected heading: ${block}`);
    else (sections.at(-1)?.paragraphs ?? intro).push(block.replace(/\s*\n\s*/g, " "));
  }
  if (sections.length !== ABOUT_SECTION_IDS.length) throw new Error(`expected ${ABOUT_SECTION_IDS.length} sections, found ${sections.length}`);
  return { title, description, intro, sections: sections.map((section, i) => ({ id: ABOUT_SECTION_IDS[i], ...section })) };
}

export function readAboutCopy(root = resolve(fileURLToPath(import.meta.url), "../../..")) {
  return Object.fromEntries(ABOUT_LOCALES.map((locale) => [locale, parseAboutMarkdown(readFileSync(resolve(root, "docs/editorial/about-page", `${locale}.md`), "utf8"))]));
}

export function renderAboutModule(copy) {
  return `// Generated by scripts/seo/about-content.mjs from docs/editorial/about-page/*.md. Do not edit.
import type { GuideLocale } from "../guides/locales.ts";

export type AboutSection = { id: string; heading: string; paragraphs: readonly string[] };
export type AboutCopy = { title: string; description: string; intro: readonly string[]; sections: readonly AboutSection[] };

export const ABOUT_CONTENT: Readonly<Record<GuideLocale, AboutCopy>> = ${JSON.stringify(copy, null, 2)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(fileURLToPath(import.meta.url), "../../../src/about/aboutContent.ts");
  writeFileSync(out, renderAboutModule(readAboutCopy()), "utf8");
  console.log(`wrote ${out}`);
}
